def generate_content(title, core_poem, pain_point):
    """生成新的8幕结构内容"""
    # 解析核心诗词，提取诗词标题和作者
    poem_title = ''
    poem_author = ''
    poem_text = ''
    
    # 简单解析格式，例如 "李白《将进酒》「天生我材必有用，千金散尽还复来」"
    match = re.search(r'(.+?)《(.+?)》「(.+?)」', core_poem)
    if match:
        poem_author = match.group(1)
        poem_title = match.group(2)
        poem_text = match.group(3)
    else:
        # 如果没有匹配，使用原样
        poem_title = '诗词标题'
        poem_author = '诗人'
        poem_text = core_poem
    
    # 生成新内容
