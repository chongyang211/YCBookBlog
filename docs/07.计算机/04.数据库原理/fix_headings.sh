#!/bin/bash
# batch fix long headings >8 chars in all 10 files
DIR="/Users/yc/YCBookBlog/docs/07.计算机/04.数据库原理"

fix_file() {
  local f="$1"
  shift
  # each arg is old_text|||new_text
  for pair in "$@"; do
    old="${pair%%|||*}"
    new="${pair##*|||}"
    # Replace in headings (## and ### only)
    sed -i '' "s/^## $old$/## $new/g" "$f"
    sed -i '' "s/^### $old$/### $new/g" "$f"
    # Replace in TOC links: [text](#anchor)
    # For simple cases where old==anchor display text
    ancor_old=$(echo "$old" | sed 's/ /%20/g; s/——/-/g; s/—/-/g; s/→/-/g; s/\/\//g; s/--/-/g')
    ancor_new=$(echo "$new" | sed 's/ /%20/g; s/——/-/g; s/—/-/g; s/→/-/g; s/\/\//g; s/--/-/g')
    sed -i '' "s/\[$old\](\#$ancor_old)/[$new](\#$ancor_new)/g" "$f"
  done
}

