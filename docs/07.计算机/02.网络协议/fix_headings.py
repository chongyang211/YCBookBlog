def get_short_text(original, h_type="h2"):
    """去除编号前缀后用 mapping 获取短文本"""
    # 去掉中文和英文混合的编号前缀
    # ## 01.XXX
    # ## 02.XXX
    # ### 1.1 XXX
    # ### 2.1 XXX
    if h_type == "h2":
        m = re.match(r'^##\s+\d+\.[\s]*(.*)', original)
    else:
        m = re.match(r'^###\s+\d+\.\d+[\s]*(.*)', original)
    
    if not m:
        return None
    
    text = m.group(1).strip()
    # 去掉引号
    text = text.replace('"', '').replace('"', '').replace("'", "").replace("'", "")
    
    mapping = H2_MAP if h_type == "h2" else H3_MAP
    if text in mapping:
        return mapping[text]
    
    # 不在映射中，检查长度是否在4-8字
    chinese_chars = len([c for c in text if '\u4e00' <= c <= '\u9fff'])
    total_chars = len(text.replace(' ', ''))
    
    # 如果中文在4-8字且总长度也符合，保留
    if 4 <= total_chars <= 8:
        return text
    
    # 尝试截取前4-8个字符（如果有中文超长的情况）
    # 对于太长的，取前几个有意义的字符
    if total_chars > 8:
        # 取前6个字符
        return text[:6]
    
    # 太短的话保留原样（因为映射中已尽量覆盖）
    return text


def process_file(filepath):
    """处理单个文件"""
    with open(filepath, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    new_lines = []
    changes = []
    
    for i, line in enumerate(lines):
        stripped = line.rstrip('\n')
        
        # 处理二级标题 ##
        if re.match(r'^##\s+\d+\.', stripped):
            new_text = get_short_text(stripped, "h2")
            if new_text:
                new_line = f"## {new_text}\n"
                if new_line != line:
                    changes.append((i+1, stripped, new_line.rstrip('\n')))
                new_lines.append(new_line)
            else:
                new_lines.append(line)
        
        # 处理三级标题 ###
        elif re.match(r'^###\s+\d+\.\d+', stripped):
            new_text = get_short_text(stripped, "h3")
            if new_text:
                new_line = f"### {new_text}\n"
                if new_line != line:
                    changes.append((i+1, stripped, new_line.rstrip('\n')))
                new_lines.append(new_line)
            else:
                new_lines.append(line)
        
        else:
            new_lines.append(line)
    
    if changes:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.writelines(new_lines)
        print(f"\n📄 {os.path.basename(filepath)} ({len(changes)} changes):")
        for lineno, old, new in changes:
            print(f"  L{lineno}: {old}")
            print(f"        → {new}")
    else:
        print(f"\n📄 {os.path.basename(filepath)}: no changes")


def main():
    md_files = sorted([f for f in os.listdir(SCRIPT_DIR) if f.endswith('.md')])
    
    for md_file in md_files:
        filepath = os.path.join(SCRIPT_DIR, md_file)
        process_file(filepath)


if __name__ == "__main__":
    main()
