# fix headings in a file: old|||new pairs
fix() {
  local f="$1"; shift
  for pair in "$@"; do
    old="${pair%%|||*}"; new="${pair##*|||}"
    sed -i '' "s/^## $old$/## $new/g" "$f"
    sed -i '' "s/^### $old$/### $new/g" "$f"
  done
}

