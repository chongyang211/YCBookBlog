def process_file(filename, all_replacements):
    path = DIR + "/" + filename
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    old_content = content
    for old, new in all_replacements:
        # Only replace actual heading lines and TOC lines, not anchor-only references
        # Replace heading lines: ## old or ### old
        content = content.replace(f"\n## {old}", f"\n## {new}")
        content = content.replace(f"\n### {old}", f"\n### {new}")
        # Replace TOC entries: [old](#
        content = content.replace(f"[{old}](#", f"[{new}](#")
    
    if content != old_content:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"  ✅ {filename}: 已更新")
    else:
        print(f"  ⚠️ {filename}: 无变化")


