// ----------------------------------------------------------------------------
// 【教学定位】对应教程§10 Step 10.1"计数器变 1837"的造 BUG 高峰：
//   两线程各加 1000 次裸 int，期望 2000 —— 实际多次运行常小于 2000。
// 【根因】++counter 是"读-改-写"三步指令序列，线程 A 读完被切走、
//   线程 B 也读同一个旧值 → 两次自增只生效一次（丢失更新）。
// 【对比】Store 用 shared_mutex 后 stress.cpp 压测零丢失 ——
//   本文件就是"为什么需要锁"的最直观对照组。
// ============================================================================

// 数据竞争现场：两线程各加 1000 次，期望 2000，实际可能 < 2000
// 这是"为什么需要锁"的最直观演示，跑几次能看到不同结果。
#include <iostream>
#include <thread>

int counter = 0;   // 裸变量，未保护
// 全局 + 裸 int + 无锁：三个条件凑齐数据竞争 ——
// 编译开 -O2 时甚至可能被优化成"先算好再加"（更彻底的错乱）

int main() {
    std::thread t1([] { for (int i = 0; i < 1000; ++i) ++counter; });
    std::thread t2([] { for (int i = 0; i < 1000; ++i) ++counter; });
    // 两个 lambda 都捕全局变量（无需捕获列表）—— 对同一内存位置并发 RMW
    t1.join();
    t2.join();
    std::cout << "counter = " << counter << " (expected 2000)\n";
    // 多跑几次：2000 / 1993 / 1837…… 每次不同 —— 竞态的"不确定性"签名
    return 0;
}
