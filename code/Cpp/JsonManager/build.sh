
#!/bin/bash
# ============================================================================
# 【文件定位】build.sh —— 一键编译并运行（最原始的构建方式）
# ----------------------------------------------------------------------------
# 【技术原理】
#   - 五个 .cpp 显式点名（对比 *.cpp 通配：精确可控，不会误卷测试文件；
#     新加源文件要记得来这里补一行 —— CMake 同理）。
#   - -std=c++17 必须：variant/optional/string_view 都是 C++17 特性，缺了直接编译失败。
# 【改进建议】编译与运行之间没有 && 连接 —— 编译失败仍会跑旧二进制（误导）；
#   建议改成 g++ ... -o jsonkv && ./jsonkv（BankSystem 的 build.sh 就是这么写的）。
# 【使用提示】首次需 chmod +x build.sh。
# ============================================================================

g++ -std=c++17 main.cpp JsonNode.cpp JsonParser.cpp JsonWriter.cpp KvDatabase.cpp -o jsonkv
./jsonkv
