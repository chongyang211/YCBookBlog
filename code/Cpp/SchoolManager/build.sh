
#!/bin/bash
# ============================================================================
# 【文件定位】build.sh —— 一键编译并运行的脚本（最原始的构建方式）
# ----------------------------------------------------------------------------
# 【技术原理】g++ 单命令编译：
#   - 所有 .cpp 一起交给编译器：每个源文件是一个"翻译单元"，先各自编译成
#     目标文件（.o），再由链接器合并成可执行文件 campus_system；
#   - 头文件（.h）不直接出现在命令行中——它们通过 #include 被"文本展开"进各 .cpp。
# 【参数说明】-std=c++17：启用 C++17 标准（项目用到了结构化绑定 auto& [k,v]、
#   dynamic_pointer_cast 等新特性，C++11/14 无法编译通过）。
# 【局限】改一个文件也要全量重编；CMakeLists.txt 是它的工程化升级版。
# 【使用提示】首次运行需要可执行权限：chmod +x build.sh，之后 ./build.sh 即可。
# ============================================================================

# 编译：列出全部源文件（顺序不影响结果，链接器自动解析符号引用），-o 指定输出名
g++ -std=c++17 main.cpp User.cpp Student.cpp Admin.cpp Teacher.cpp Computer.cpp Speech.cpp Reservation.cpp CampusSystem.cpp -o campus_system
# 编译成功后立即运行（两条命令无 && 连接：即使编译失败也会尝试运行旧的二进制，
# 更稳妥的写法是 g++ ... -o campus_system && ./campus_system）
./campus_system
