#include "User.h"    // 对应头文件（必须最先包含，可自查头文件能否独立编译）

// TODO：为什么这样写构造函数？
// 【解答·技术原理】
//   1. 参数全部 const std::string&（const 引用传参）：
//      避免按值拷贝三个字符串；const 承诺函数内不修改实参。
//   2. 用初始化列表 ": userId(id), ..." 而不是函数体内赋值：
//      成员在进入函数体之前必须先完成初始化——函数体内赋值等于
//      "先默认构造 string（空串），再执行一次赋值拷贝"，白白多一步；
//      初始化列表则是"直接用实参拷贝构造"，一气呵成，性能更优。
//   3. 基类成员（userId 等）是 protected，任何外部函数都不能访问，
//      所以必须由 User 自己（或派生类）在构造时写入。
// 作用域解析符 "User::" 表明这是"类外定义"的成员函数实现。
User::User(const std::string& id, const std::string& name, const std::string& pwd)
    : userId(id), userName(name), password(pwd) {
    // 构造即审计：打印创建日志便于调试观察对象生命周期
    // 【修复说明】原始代码写作 cout/endl（无 std:: 前缀）在部分标准库实现下
    //             （如 macOS 的 libc++）会编译失败，已规范为 std::cout / std::endl。
    std::cout << "[User] 创建账户 " << id << " - " << name << std::endl;
}


