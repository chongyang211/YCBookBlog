// ============================================================================
// 【文件定位】main.cpp —— 程序入口（组装层）：创建通讯录 + 进入菜单循环
// ----------------------------------------------------------------------------
// 【设计思路】入口函数保持"三行全貌"：
//   定义数据 → 交给主流程 → 返回退出码。所有业务细节都下沉到
//   StudentManager.cpp，main 只负责"把哪些东西连接起来"。
// ============================================================================

#include "StudentManager.h"  // 引入结构体定义（Person/AddressBooks）与函数声明

int main() {
    AddressBooks abs;          // 创建通讯录（size 已在结构体内初始化为 0）
    // 【技术原理】栈上分配：AddressBooks 含 100 个 Person（3 个 string + 2 个 int），
    //   约几 KB，栈空间完全放得下；变量生命周期贯穿整个 main ——
    //   正好"活得比所有业务函数都久"，指针传参不会悬空。
    // 【初始化】size = 0 由类内默认初始化（NSDMI）保证，无需手写 abs.size = 0。
    showMainSelect(&abs);      // 进入菜单循环
    // 【传参】&abs 取地址转成指针：把"通讯录本体"递进主流程，
    //   后续所有业务函数经由这个指针改的都是同一份原件。
    return 0;                  // 0 = 正常退出（非 0 常用于告知操作系统"出错了"）
}
