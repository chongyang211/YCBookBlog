
#!/bin/bash
# ============================================================================
# 【文件定位】build.sh —— 一键编译并运行的脚本（最原始的构建方式）
# ----------------------------------------------------------------------------
# 【技术原理】
#   - *.cpp 通配符：把目录下所有源文件一起交给 g++，每个 .cpp 先编译成目标
#     文件再由链接器合并 —— 无需逐个点名（新加 cpp 也不用改本脚本）；
#     代价是"无关的 cpp 也会被卷入"（如以后加 test.cpp 就会混进来）。
#   - -std=c++17：启用 C++17（static constexpr 类内初始化等特性必需）。
#   - && 链：前一步成功才执行下一步 —— 编译失败不会运行旧二进制（好习惯）。
# 【使用提示】首次运行需可执行权限：chmod +x build.sh，之后 ./build.sh 即可。
# ============================================================================

# 编译全部源文件为 bank_system，成功后打印提示并立即运行
g++ -std=c++17 *.cpp -o bank_system && echo "✅ 编译成功" && ./bank_system
