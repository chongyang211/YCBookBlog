#!/usr/bin/env bash
#
# scripts/demo-all.sh — 一键跑全部 12 盒
# 跑完产物：
#   out/csv/*.csv     每盒的数据
#   out/plots/*.png   汇总图表
#   out/report.html   HTML 聚合报告
#
set -e
cd "$(dirname "$0")/.."
mkdir -p out/csv out/plots

BIN=./build/bin
echo "==================== MiniLab demo-all ===================="

# --- 盒 ① 进程 ---
echo
echo "=== Box ① box_proc (skip interactive REPL) ==="
echo "  跳过交互：生产环境自己跑 ./build/bin/box_proc + zombie 命令"

# --- 盒 ② 协程 ---
echo
echo "=== Box ② box_coro ==="
rm -f out/csv/box_coro.csv
for N in 1000 10000 100000; do
    $BIN/box_coro $N 2048 || true
done

# --- 盒 ③ 调度器 ---
echo
echo "=== Box ③ box_sched ==="
rm -f out/csv/box_sched.csv
$BIN/box_sched demo/sched/mixed.task all || true

# --- 盒 ④ IPC ---
echo
echo "=== Box ④ box_ipc ==="
: > out/csv/box_ipc.csv
echo "ipc,metric,value,unit" > out/csv/box_ipc.csv

parse_ipc() {
    local name="$1"
    while IFS= read -r line; do
        echo "$line"
        if echo "$line" | grep -q 'MB/s'; then
            v=$(echo "$line" | sed -E 's/.* = ([0-9.]+) MB\/s.*/\1/')
            echo "$name,bandwidth,$v,MB/s" >> out/csv/box_ipc.csv
        elif echo "$line" | grep -q 'us/rtt'; then
            v=$(echo "$line" | sed -E 's/.* = ([0-9.]+) us\/rtt.*/\1/')
            echo "$name,latency,$v,us" >> out/csv/box_ipc.csv
        fi
    done
}
[ -x $BIN/bench_pipe ] && $BIN/bench_pipe all | parse_ipc pipe
[ -x $BIN/bench_uds  ] && $BIN/bench_uds  all | parse_ipc uds
[ -x $BIN/bench_shm  ] && $BIN/bench_shm  all | parse_ipc shm
[ -x $BIN/bench_mq   ] && $BIN/bench_mq       | parse_ipc mq || true

# --- 盒 ⑤ 死锁 ---
echo
echo "=== Box ⑤ box_lock ==="
rm -f out/csv/box_lock.csv
for M in order parity trylock; do
    $BIN/box_lock $M 2 || true
done
# bug 模式会 _Exit(2)，用 || true 让脚本继续
$BIN/box_lock bug 3 || true

# --- 盒 ⑥ malloc ---
echo
echo "=== Box ⑥ box_malloc (非交互测试) ==="
echo -e "stress 32,1048576 500 128\nstat\nreap\nstat\nbench 1000000\nquit" \
    | $BIN/box_malloc || true

# --- 盒 ⑦ 页替换 ---
echo
echo "=== Box ⑦ box_vm ==="
rm -f out/csv/box_vm.csv
$BIN/box_vm belady || true

# --- 盒 ⑧ FS ---
echo
echo "=== Box ⑧ box_fs ==="
[ -x $BIN/mkfs ] && $BIN/mkfs out/disk.img
echo -e "mount out/disk.img\nwrite a 1000\nwrite b 2000\nls\nstat\nopen a\nrm a\nstat\nclose 3\nstat\nquit" \
    | $BIN/box_fs || true

# --- 盒 ⑨ IO（可选，启服务 + 压测）---
if [ -x $BIN/echo_select ]; then
    echo
    echo "=== Box ⑨ box_io (brief) ==="
    $BIN/echo_select 19001 &
    SPID=$!
    sleep 0.3
    $BIN/stress_client 19001 1000 10 || true
    kill $SPID 2>/dev/null || true
    wait $SPID 2>/dev/null || true
fi

# --- 盒 ⑩⑪⑫ 需要 Linux root，demo 中跳过 ---
if [ -x $BIN/mycgrp ]; then
    echo
    echo "=== Box ⑫ mycgrp（信息展示；真实限额需 sudo，脚本中跳过）==="
    $BIN/mycgrp || true
fi

# --- 画图 ---
echo
echo "==================== plotting ===================="
if command -v python3 >/dev/null && python3 -c "import pandas, matplotlib" 2>/dev/null; then
    python3 tools/plot.py all || true
else
    echo "(skip plot: pip3 install pandas matplotlib)"
fi

# --- HTML 报告 ---
cat > out/report.html <<EOF
<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>MiniLab Report</title>
<style>
body { font-family: -apple-system, Segoe UI, sans-serif; max-width: 1000px; margin: 2em auto; padding: 0 1em; }
h1 { border-bottom: 2px solid #333; padding-bottom: .3em; }
h2 { margin-top: 2em; color: #333; }
img { max-width: 100%; border: 1px solid #ddd; border-radius: 4px; margin: .5em 0; }
.box { background: #f6f8fa; padding: 1em; border-radius: 6px; margin-bottom: 1em; }
code { background: #eee; padding: 2px 4px; border-radius: 3px; }
</style></head><body>
<h1>MiniLab · 12 Boxes Report</h1>
<p>Generated by <code>scripts/demo-all.sh</code>. Full guide → <code>packages/website/04.计算机/03.操作系统原理/12.MiniLab操作系统实验盒.md</code>.</p>
EOF

for b in sched vm coro lock ipc; do
    f="out/plots/box_${b}.png"
    if [ -f "$f" ]; then
        rel=$(basename "$f")
        cat >> out/report.html <<EOF
<div class="box"><h2>Box ${b}</h2><img src="plots/${rel}" alt="${b}"></div>
EOF
    fi
done

cat >> out/report.html <<EOF
</body></html>
EOF

echo
echo "==================== done ===================="
echo "report: out/report.html"
echo "csv:    out/csv/*.csv"
echo "plots:  out/plots/*.png"
