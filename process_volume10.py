    if match:
        poem_author = match.group(1)
        poem_title = match.group(2)
        poem_text = match.group(3)
    else:
        # 如果没有匹配，使用原样
        poem_title = '诗词标题'
        poem_author = '诗人'
        poem_text = core_poem
    
